// Read-aloud on the web build: Jude (recorded locally in the alec voice) plays, the spoken verse tints, the word
// highlight moves, next/prev verse jump, pause holds. Needs a server whose BEREAN_DATA has tts/alec/65-1.*.
import { chromium } from 'playwright'
const base = process.env.BASE ?? 'http://127.0.0.1:8787'
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] })
const ctx = await browser.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await ctx.addInitScript(() => localStorage.setItem('berean_prefs', JSON.stringify({ theme: 'paper', themeLight: 'paper', themeDark: 'slate', font: 'serif', fontSize: 19, lineHeight: 1.6, letterSpacing: 0, wordSpacing: 0, verseNumbers: true, paragraphs: true, showNotes: true, reduceMotion: true, align: 'center', width: 'medium', ttsVoice: 'alec', ttsSpeed: 1, ttsNumbers: true, ttsHeading: true, ttsPause: 'short', ttsWord: true, ttsAutoNext: false, ttsDevice: false })))
const page = await ctx.newPage()
const errors = []; page.on('pageerror', e => errors.push(e.message))
await page.goto(base + '/read/65/1', { waitUntil: 'networkidle' })
await page.waitForSelector('text=Jude')
await page.getByLabel('Read aloud').click()
await page.waitForTimeout(2500)
const bar = async () => (await page.locator('text=/^Jude 1(:\\d+)?$/').first().textContent().catch(() => '?'))
console.log('bar after 2.5s:', await bar(), '| status text:', await page.getByText(/Alec · 1×|Loading|Device voice|Could not/).first().textContent().catch(() => '?'))
await page.waitForTimeout(9000)
const spokenWords = async () => page.evaluate(() => [...document.querySelectorAll('span')].filter(s => s.style.backgroundColor && s.style.backgroundColor !== 'transparent' && s.textContent && s.textContent.length < 25 && getComputedStyle(s).borderRadius === '3px').map(s => s.textContent))
console.log('bar after 11.5s:', await bar(), '| highlighted word(s):', await spokenWords())
await page.screenshot({ path: '/tmp/bdb-ui/player-playing.png' })
await page.getByLabel('Next verse').click(); await page.waitForTimeout(1500)
console.log('after next:', await bar())
await page.getByLabel('Pause').click(); await page.waitForTimeout(300)
const b1 = await bar(); await page.waitForTimeout(2500); const b2 = await bar()
console.log('paused holds verse:', b1 === b2, b1, '| play button present:', await page.getByLabel('Play').isVisible().catch(() => false))
await page.getByLabel('Play').click(); await page.waitForTimeout(1500)
console.log('resumed:', await page.getByLabel('Pause').isVisible().catch(() => false))
await page.getByLabel('Stop reading').click(); await page.waitForTimeout(500)
console.log('bar gone after stop:', !(await page.getByLabel('Stop reading').isVisible().catch(() => false)))
console.log(errors.length ? 'ERRORS: ' + errors.join(' | ') : 'no page errors')
await browser.close()
