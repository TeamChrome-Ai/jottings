import { chromium } from 'playwright'
const T = process.argv[2]
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 1000, height: 800 } })
await ctx.addInitScript(t => localStorage.setItem('berean_token', t), T)
const page = await ctx.newPage()
const errors = []
page.on('pageerror', e => errors.push(e.message))
const log = {}
await page.goto('http://127.0.0.1:5173/read/1/1', { waitUntil: 'networkidle' })
await page.click('.nc >> nth=0')
await page.waitForTimeout(300)
log.noteOpen = await page.locator('.note-inline').count()
await page.screenshot({ path: '/tmp/shot-note.png' })
await page.click('text=Aa')
await page.waitForTimeout(800)
await page.click('.reader .w.has-s >> nth=1')
await page.waitForTimeout(800)
log.strongsOpen = await page.locator('.popover').count()
await page.screenshot({ path: '/tmp/shot-strongs.png' })
await page.keyboard.press('Escape')
await page.waitForTimeout(300)
log.strongsAfterEsc = await page.locator('.popover').count()
if (log.strongsAfterEsc) await page.mouse.click(5, 400)
await page.click('button[title="Reading settings"]')
await page.click('text=Dyslexic')
await page.click('text=sepia')
await page.click('text=Done')
await page.waitForTimeout(600)
log.font = await page.evaluate(() => getComputedStyle(document.querySelector('.reader')).fontFamily.slice(0, 40))
await page.screenshot({ path: '/tmp/shot-dyslexic.png' })
await page.click('#v1'); await page.click('#v2')
await page.waitForTimeout(300)
log.actions = await page.locator('.verse-actions').count()
await page.screenshot({ path: '/tmp/shot-select.png' })
console.log(JSON.stringify({ ...log, errors }))
await browser.close()
