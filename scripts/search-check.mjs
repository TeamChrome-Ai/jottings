// Misspelt references in search, the verse flash on arrival, the order of word results (Bible order | Best match),
// a book's name searched as a word with the book offered (SHOT = a 412 px still of the "song" results), and the
// absence of a public outlines tab. Exits 1 when a result-order check fails.
import { chromium } from 'playwright'
const base = process.env.BASE ?? 'http://127.0.0.1:8787'
const browser = await chromium.launch()
const ctx = await browser.newContext({ viewport: { width: 390, height: 780 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true })
await ctx.addInitScript(() => localStorage.setItem('berean_prefs', JSON.stringify({ theme: 'paper', themeLight: 'paper', themeDark: 'slate', font: 'serif', fontSize: 19, lineHeight: 1.6, letterSpacing: 0, wordSpacing: 0, verseNumbers: true, paragraphs: true, showNotes: true, reduceMotion: false, align: 'center', width: 'medium' })))
const page = await ctx.newPage()
const errors = []; page.on('pageerror', e => errors.push(e.message))
// 1. "Jhon 3:16" opens John 3 at verse 16
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('Jhon 3:16')
await page.getByRole('button', { name: 'Go' }).click()
await page.waitForURL(/\/read\/43\/3/, { timeout: 15000 }).then(() => console.log('Jhon 3:16 →', page.url())).catch(() => console.log('Jhon 3:16 did NOT navigate:', page.url()))
await page.waitForSelector('text=Nicodemus')
await page.waitForTimeout(900)
// the arrived-at verse 16 carries the selection tint while flashing
const tinted = await page.evaluate(() => [...document.querySelectorAll('div, span')].some(el => el.textContent?.startsWith('16') && getComputedStyle(el).backgroundColor !== 'rgba(0, 0, 0, 0)'))
console.log('verse 16 flashed:', tinted)
await page.screenshot({ path: '/tmp/bdb-ui/search-jhon-flash.png' })
// 2. bare misspelling offers a suggestion instead of guessing
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('Pslams')
await page.getByRole('button', { name: 'Go' }).click()
await page.waitForTimeout(1500)
console.log('did-you-mean shown:', await page.getByText('Did you mean').isVisible().catch(() => false), '| suggestion:', await page.getByRole('button', { name: 'Psalms' }).isVisible().catch(() => false))
await page.screenshot({ path: '/tmp/bdb-ui/search-pslams.png' })
// 2b. a Strong's number opens its word study in the word sheet, on The word
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('g1320')
await page.getByRole('button', { name: 'Go' }).click()
await page.getByRole('dialog').getByText('διδάσκαλος', { exact: true }).first().waitFor({ timeout: 15000 }).catch(() => {})
console.log('g1320 opens the word sheet:', await page.getByRole('dialog').getByText('G1320', { exact: true }).isVisible().catch(() => false))
await page.screenshot({ path: '/tmp/bdb-ui/search-strongs.png' })
// 2c. one word lists in Bible order (Genesis 1:1 first) and says so; Best match re-runs it in bm25 order
let failed = 0
const check = (name, ok, detail = '') => { if (!ok) failed++; console.log(`${ok ? 'ok  ' : 'FAIL'} ${name}${detail ? ` (${detail})` : ''}`) }
const refs = () => page.getByRole('link').evaluateAll(els => els.map(el => el.textContent.match(/^(?:[1-3] )?[A-Z][A-Za-z ]+? \d+:\d+/)?.[0]).filter(Boolean))
// a Segmented label is drawn twice (two inks), so its text reads doubled: match on how it starts
const selected = () => page.getByRole('radio', { checked: true }).evaluateAll(els => els.map(el => el.textContent.trim()))
const isSelected = async label => (await selected()).some(t => t.startsWith(label))
await page.goto(base + '/search', { waitUntil: 'networkidle' })
check('no order control before a search', !(await page.getByRole('radio', { name: 'Bible order' }).count()))
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('beginning')
await page.getByRole('button', { name: 'Go' }).click()
await page.getByRole('radio', { name: 'Bible order' }).waitFor({ timeout: 15000 }).catch(() => {})
await page.waitForTimeout(600)
const bible = await refs()
const count = await page.getByText(/^\d[\d,]* verses · \d+ ms/).textContent().catch(() => '')
check('"beginning": first row Genesis 1:1', bible[0] === 'Genesis 1:1', bible.slice(0, 3).join(', '))
check('Bible order is the one selected', await isSelected('Bible order'), (await selected()).join(', '))
await page.screenshot({ path: '/tmp/bdb-ui/search-order-bible.png' })
await page.getByRole('radio', { name: 'Best match' }).click()
await page.getByRole('radio', { name: 'Best match', checked: true }).waitFor({ timeout: 15000 }).catch(() => {})
await page.waitForTimeout(600)
const match = await refs()
check('Best match changes the order', match.length === bible.length && match[0] !== 'Genesis 1:1' && match.join() !== bible.join(), match.slice(0, 3).join(', '))
check('Best match is now selected', await isSelected('Best match'), (await selected()).join(', '))
check('the count is unchanged', count && (await page.getByText(/^\d[\d,]* verses · \d+ ms/).textContent()).split(' · ')[0] === count.split(' · ')[0], count)
await page.screenshot({ path: '/tmp/bdb-ui/search-order-match.png' })
// the pick holds for the next search this session, and several words say Best match on their own
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('shepherd')
await page.getByRole('button', { name: 'Go' }).click()
await page.getByText(/^\d[\d,]* verses · \d+ ms/).filter({ hasNotText: count.split(' · ')[0] }).waitFor({ timeout: 15000 }).catch(() => {})
check('the picked order holds for the next search', await isSelected('Best match'), (await selected()).join(', '))
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('faith hope love')
await page.getByRole('button', { name: 'Go' }).click()
await page.getByRole('radio', { name: 'Best match' }).waitFor({ timeout: 15000 }).catch(() => {})
await page.waitForTimeout(400)
check('several words default to Best match (a new session)', await isSelected('Best match'), (await selected()).join(', '))
// 2d. a citation still jumps straight to the chapter, whatever the order
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await page.getByPlaceholder('jn 3:16, words, or G1320').fill('rom 8:28')
await page.getByRole('button', { name: 'Go' }).click()
check('"rom 8:28" opens Romans 8', await page.waitForURL(/\/read\/45\/8/, { timeout: 15000 }).then(() => true, () => false), page.url())
// 2e. a book's name alone is a word: the hits, with the book offered in one row above them
const field = () => page.getByPlaceholder('jn 3:16, words, or G1320')
const bookRow = name => page.getByRole('button', { name, exact: true }).filter({ hasText: 'Open the book' })
const cards = () => page.getByRole('link').evaluateAll(els => els.map(el => el.textContent))
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await field().fill('song')
await page.getByRole('button', { name: 'Go' }).click()
await bookRow('Song of Songs').waitFor({ timeout: 15000 }).catch(() => {})
await page.waitForTimeout(600)
check('"song" stays on Search', new URL(page.url()).pathname === '/search', page.url())
check('"song" offers Song of Songs · Open the book', await bookRow('Song of Songs').count() === 1)
const songRefs = await refs(), songCards = await cards()
check('"song" lists verses with the word', songCards.length > 5 && songCards.every(t => /song/i.test(t)), `${songCards.length} cards`)
check('"song" is in Bible order, from before Song of Songs', await isSelected('Bible order') && songRefs[0] === 'Genesis 31:27', songRefs.slice(0, 3).join(', '))
check('"song" shows its count', await page.getByText(/^\d[\d,]* verses · \d+ ms/).isVisible().catch(() => false))
if (process.env.SHOT) { await page.setViewportSize({ width: 412, height: 915 }); await page.waitForTimeout(300); await page.screenshot({ path: process.env.SHOT }); await page.setViewportSize({ width: 390, height: 780 }) }
await bookRow('Song of Songs').click()
check('the row opens Song of Songs 1', await page.waitForURL(/\/read\/22\/1(?:\D|$)/, { timeout: 15000 }).then(() => true, () => false), page.url())
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await field().fill('song 2:1')
await page.getByRole('button', { name: 'Go' }).click()
check('"song 2:1" opens Song of Songs 2', await page.waitForURL(/\/read\/22\/2(?:\D|$)/, { timeout: 15000 }).then(() => true, () => false), page.url())
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await field().fill('mark')
await page.getByRole('button', { name: 'Go' }).click()
await bookRow('Mark').waitFor({ timeout: 15000 }).catch(() => {})
await page.waitForTimeout(600)
const markCards = await cards()
check('"mark" offers Mark and lists the word', await bookRow('Mark').count() === 1 && markCards.length > 0 && markCards.every(t => /mark/i.test(t)), `${markCards.length} cards`)
// a name the text never uses still opens the book
await page.goto(base + '/search', { waitUntil: 'networkidle' })
await field().fill('jn')
await page.getByRole('button', { name: 'Go' }).click()
check('"jn" opens John 1', await page.waitForURL(/\/read\/43\/1(?:\D|$)/, { timeout: 15000 }).then(() => true, () => false), page.url())
// 3. chapter picker: Psalms grid, last cell animates too (opacity rises from 0)
await page.goto(base + '/read/19/23', { waitUntil: 'networkidle' })
await page.waitForSelector('text=shepherd')
await page.getByText('Psalms 23').first().click()
await page.waitForTimeout(150)
const early = await page.getByText('150', { exact: true }).evaluate(el => getComputedStyle(el.parentElement.parentElement).opacity).catch(() => 'n/a')
await page.waitForTimeout(900)
const late = await page.getByText('150', { exact: true }).evaluate(el => getComputedStyle(el.parentElement.parentElement).opacity).catch(() => 'n/a')
console.log('Psalm 150 cell opacity early/late:', early, late)
await page.screenshot({ path: '/tmp/bdb-ui/picker-psalms.png' })
// 4. no public tab on outlines
await page.goto(base + '/outlines', { waitUntil: 'networkidle' })
await page.waitForTimeout(800)
console.log('Public tab present:', await page.getByRole('radio', { name: 'Public' }).isVisible().catch(() => false), '| note shown:', await page.getByText('no public directory').isVisible().catch(() => false))
console.log(errors.length ? 'ERRORS: ' + errors.join(' | ') : 'no page errors')
await browser.close()
console.log(failed ? `${failed} FAILED` : 'order checks passed')
process.exit(failed || errors.length ? 1 : 0)
