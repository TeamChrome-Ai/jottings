// After `expo export --platform web`: write dist/sw.js with the precache list of the app shell.
// Runtime: cache-first for /bible/* (and /bible1890/*, docs/EDITION.md; /bible-fr/*, /bible-de/*, docs/LANGUAGES.md) chapter JSON and hashed _expo assets,
// network-first for the HTML shell, never cache /api. A chapter is kept only when the server marks it immutable: while
// the 1890 edition is on, /bible/* answers with its 1890 file and no-cache, which must not stand for the 1961 one later.
// Idle registration happens in app/_layout.tsx.
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
const dist = process.argv[2] ?? 'dist'
const files = []
const walk = d => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else files.push('/' + relative(dist, p).split('\\').join('/')) } }
walk(dist)
// Fonts: only the faces every visitor loads at start (Literata, from public/fonts by the page's head). OpenDyslexic
// is fetched only once chosen, and the fetch handler caches it then.
const startupFont = f => /^\/fonts\/Literata-[^/]+\.woff2$/.test(f)
const shell = files.filter(f => /^\/_expo\/static\/(js|css)\//.test(f) || f === '/index.html' || f === '/manifest.json' || startupFont(f)).filter(f => !f.endsWith('.br') && !f.endsWith('.map'))
const version = Date.now().toString(36)
const sw = `/* generated by scripts/make-sw.mjs */
const V = 'berean-shell-${version}';
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', e => { e.waitUntil(caches.open(V).then(c => c.addAll(SHELL)).then(() => self.skipWaiting())); });
self.addEventListener('activate', e => { e.waitUntil(caches.keys().then(ks => Promise.all(ks.filter(k => k.startsWith('berean-shell-') && k !== V).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', e => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin || u.pathname.startsWith('/api/')) return;
  const chapter = /^\\/bible(1890|-fr|-de)?\\/\\d+\\/\\d+\\.json$/.test(u.pathname);
  if (u.pathname.startsWith('/_expo/') || u.pathname.startsWith('/assets/') || u.pathname.startsWith('/fonts/') || chapter) {
    e.respondWith(caches.match(e.request).then(hit => hit || fetch(e.request).then(r => { if (r.ok && (!chapter || (r.headers.get('cache-control') || '').includes('immutable'))) { const copy = r.clone(); caches.open(chapter ? 'berean-bible' : V).then(c => c.put(e.request, copy)); } return r; })));
    return;
  }
  if (e.request.mode === 'navigate' || u.pathname.endsWith('.html') || u.pathname === '/') {
    e.respondWith(fetch(e.request).then(r => { const copy = r.clone(); caches.open(V).then(c => c.put('/index.html', copy)); return r; }).catch(() => caches.match('/index.html')));
  }
});
`
writeFileSync(join(dist, 'sw.js'), sw)
console.log(`sw.js: ${shell.length} shell files precached`)
