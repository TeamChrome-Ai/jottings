export interface VotdRef { book: number; chapter: number; v1: number; v2?: number }
export function parseVotd(s: string): VotdRef {
  const [b, c, v] = s.split(':'); const [v1, v2] = v.split('-').map(Number)
  return { book: Number(b), chapter: Number(c), v1, v2 }
}
/** Day-of-year index, shifted by the year so the same date shows a different verse next year. */
export function votdIndex(d: Date, n = VOTD_REFS.length): number {
  const start = Date.UTC(d.getFullYear(), 0, 0)
  const day = Math.floor((Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) - start) / 86_400_000)
  return (day + d.getFullYear() * 131) % n
}
export const votdFor = (d = new Date()): VotdRef => parseVotd(VOTD_REFS[votdIndex(d)])
/** Darby keeps a verse that continues a sentence in lower case; on its own it opens with a capital. */
export function presentVotd(text: string): string {
  const t = text.trim().replace(/^[—–-]\s*/, '')
  return t.charAt(0).toUpperCase() + t.slice(1)
}
